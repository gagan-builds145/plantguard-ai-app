type I18nContextValue = {
  language: string;
  setLanguage: (code: string) => void;
  t: (key: MessageKey) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const profile = useQuery(api.farmers.getProfile);
  const [language, setLanguageState] = useState("en");

  // Adopt the language saved on the farmer profile once it loads (or changes).
  useEffect(() => {
    if (profile?.language && MESSAGES[profile.language]) {
      setLanguageState(profile.language);
    }
  }, [profile?.language]);

  const setLanguage = useCallback((code: string) => {
    setLanguageState(MESSAGES[code] ? code : "en");
  }, []);

  const value = useMemo<I18nContextValue>(() => {
    const table = MESSAGES[language] ?? en;
    return {
      language,
      setLanguage,
      t: (key) => table[key] ?? en[key] ?? key,
    };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    // Safe fallback so a component rendered outside the provider still works.
    return {
      language: "en",
      setLanguage: () => {},
      t: (key: MessageKey) => en[key] ?? key,
    } satisfies I18nContextValue;
  }
  return context;
}

